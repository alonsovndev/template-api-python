import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Connection, inspect, text

from tests.support.postgres import downgrade, migration_configuration, upgrade
from tests.support.postgres import test_database as isolated_database

pytestmark = pytest.mark.postgres


def check_schema(connection: Connection, configuration: Config) -> None:
    configuration.attributes["connection"] = connection
    command.check(configuration)


async def test_production_baseline_has_no_business_tables_or_schema_drift() -> None:
    async with isolated_database(include_example=False) as engine, engine.begin() as connection:
        tables = await connection.run_sync(lambda database: inspect(database).get_table_names())
        assert tables == ["alembic_version"]
        revision = await connection.scalar(text("SELECT version_num FROM alembic_version"))
        assert revision == "0001_baseline"
        await connection.run_sync(check_schema, migration_configuration(include_example=False))


async def test_example_schema_supports_downgrade_and_reupgrade() -> None:
    configuration = migration_configuration()
    async with isolated_database() as engine, engine.begin() as connection:
        tables = await connection.run_sync(lambda database: inspect(database).get_table_names())
        assert set(tables) == {"alembic_version", "items"}
        await connection.run_sync(check_schema, configuration)
        await connection.run_sync(downgrade, configuration)
        tables = await connection.run_sync(lambda database: inspect(database).get_table_names())
        assert tables == ["alembic_version"]
        assert await connection.scalar(text("SELECT count(*) FROM alembic_version")) == 0
        await connection.run_sync(upgrade, configuration)
        await connection.run_sync(check_schema, configuration)
        revision = await connection.scalar(text("SELECT version_num FROM alembic_version"))
        assert revision == "0002_example_item"


async def test_alembic_reports_schema_drift() -> None:
    configuration = migration_configuration()
    async with isolated_database() as engine, engine.begin() as connection:
        await connection.execute(text("ALTER TABLE items ADD COLUMN unexpected_column text"))
        with pytest.raises(AutogenerateDiffsDetected):
            await connection.run_sync(check_schema, configuration)
